from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
import plotly.express as px
import streamlit as st

from src.analysis.market_analysis import (
    kpi_summary,
    monthly_revenue,
    numeric_summary,
    revenue_by_country,
    top_products,
)
from src.data.dashboard_data import REQUIRED_UPLOADS, load_uploaded_datasets
from src.database.connection import test_connection
from src.database.load_to_mysql import load_processed_data
from src.models.customer_segmentation import segment_customers
from src.pipeline.data_pipeline import main as run_pipeline
from src.recommendations.product_recommender import ProductRecommender


PROJECT_ROOT = Path(__file__).resolve().parent
PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"

st.set_page_config(
    page_title="Retail Market Intelligence",
    page_icon="R",
    layout="wide",
)


@st.cache_data(ttl=3600)
def load_sales() -> pd.DataFrame:
    frame = pd.read_csv(
        PROCESSED_DIR / "eligible_sales.csv",
        parse_dates=["InvoiceDate"],
        dtype={"Invoice": "string", "StockCode": "string", "Description": "string"},
    )
    return frame


@st.cache_data(ttl=3600)
def load_rfm() -> pd.DataFrame:
    return pd.read_csv(PROCESSED_DIR / "customer_rfm.csv")


@st.cache_data(ttl=3600)
def load_baskets() -> pd.DataFrame:
    return pd.read_csv(PROCESSED_DIR / "market_basket_transactions.csv")


def format_currency(value: float) -> str:
    if abs(value) >= 1_000_000:
        return f"${value / 1_000_000:.2f}M"
    if abs(value) >= 1_000:
        return f"${value / 1_000:.1f}K"
    return f"${value:,.2f}"


uploaded_datasets = st.session_state.get("processed_upload_datasets")
local_data_available = all(
    (PROCESSED_DIR / filename).is_file()
    for filename in REQUIRED_UPLOADS
)
sales_available = local_data_available or uploaded_datasets is not None
if not sales_available:
    st.title("Retail Market Intelligence")
    st.warning("Processed data was not found in this deployment.")
    st.write(
        "Upload the three processed CSV files generated by the pipeline. "
        "Files are kept only in this app session and are not committed or stored permanently."
    )
    uploads = st.file_uploader(
        "Processed datasets",
        type=["csv"],
        accept_multiple_files=True,
        key="processed_dataset_uploads",
    )
    if uploads:
        upload_map = {Path(upload.name).name: upload.getvalue() for upload in uploads}
        missing_uploads = sorted(REQUIRED_UPLOADS.difference(upload_map))
        if missing_uploads:
            st.info("Still needed: " + ", ".join(missing_uploads))
        else:
            try:
                loaded_datasets = load_uploaded_datasets(upload_map)
            except (ValueError, pd.errors.ParserError, KeyError) as exc:
                st.error(f"Could not load the uploaded datasets: {exc}")
            else:
                st.session_state["processed_upload_datasets"] = loaded_datasets
                st.rerun()
    if (PROJECT_ROOT / "data" / "raw" / "archive.zip").is_file() and st.button(
        "Run preprocessing pipeline"
    ):
        with st.spinner("Processing 1M+ retail records..."):
            result = run_pipeline([])
        if result == 0:
            st.cache_data.clear()
            st.success("Preprocessing completed. Refresh the page.")
else:
    if uploaded_datasets is not None:
        sales, rfm, baskets = uploaded_datasets
    else:
        sales = load_sales()
        rfm = load_rfm()
        baskets = load_baskets()

    st.title("Retail Market Intelligence")
    st.caption("Sales analytics, customer segmentation, and product recommendations")

    min_date = sales["InvoiceDate"].min().date()
    max_date = sales["InvoiceDate"].max().date()
    country_options = sorted(str(value) for value in sales["Country"].dropna().unique())

    with st.sidebar:
        st.header("Filters")
        date_range = st.date_input(
            "Transaction period",
            value=(min_date, max_date),
            min_value=min_date,
            max_value=max_date,
        )
        selected_countries = st.multiselect(
            "Countries",
            options=country_options,
            default=[],
            placeholder="All countries",
        )

    if isinstance(date_range, tuple) and len(date_range) == 2:
        start_date, end_date = date_range
    else:
        start_date, end_date = min_date, max_date

    filtered = sales[
        (sales["InvoiceDate"].dt.date >= start_date)
        & (sales["InvoiceDate"].dt.date <= end_date)
    ]
    if selected_countries:
        filtered = filtered[filtered["Country"].isin(selected_countries)]

    tab_overview, tab_segments, tab_basket, tab_recommendations, tab_operations = st.tabs(
        ["Overview", "Customer Segments", "Market Basket", "Recommendations", "Data Operations"]
    )

    with tab_overview:
        kpis = kpi_summary(filtered)
        columns = st.columns(4)
        columns[0].metric("Revenue", format_currency(kpis["revenue"]))
        columns[1].metric("Orders", f"{kpis['orders']:,}")
        columns[2].metric("Customers", f"{kpis['customers']:,}")
        columns[3].metric("Products", f"{kpis['products']:,}")

        monthly = monthly_revenue(filtered)
        if not monthly.empty:
            left, right = st.columns(2)
            with left:
                fig = px.line(monthly, x="Month", y="Revenue", markers=True, title="Monthly Revenue")
                fig.update_layout(yaxis_tickprefix="$")
                st.plotly_chart(fig, use_container_width=True)
            with right:
                fig = px.bar(
                    revenue_by_country(filtered),
                    x="Country",
                    y="Revenue",
                    title="Revenue by Country",
                )
                fig.update_layout(xaxis_tickangle=-35, yaxis_tickprefix="$")
                st.plotly_chart(fig, use_container_width=True)

        product_table = top_products(filtered)
        st.subheader("Top Selling Products")
        st.dataframe(product_table, use_container_width=True, hide_index=True)

    with tab_segments:
        cluster_count = st.slider("Number of customer segments", 3, 8, 5)
        try:
            segmented, _ = segment_customers(rfm, cluster_count)
        except ValueError as exc:
            st.error(str(exc))
        else:
            segment_summary = (
                segmented.groupby("Segment", as_index=False)
                .agg(
                    Customers=("Customer ID", "count"),
                    AverageRecency=("RecencyDays", "mean"),
                    AverageFrequency=("Frequency", "mean"),
                    AverageMonetary=("Monetary", "mean"),
                )
                .sort_values("AverageMonetary", ascending=False)
            )
            left, right = st.columns(2)
            with left:
                fig = px.bar(
                    segment_summary,
                    x="Segment",
                    y="Customers",
                    title="Customers by Segment",
                    color="Segment",
                )
                st.plotly_chart(fig, use_container_width=True)
            with right:
                fig = px.scatter(
                    segmented,
                    x="RecencyDays",
                    y="Monetary",
                    size="Frequency",
                    color="Segment",
                    title="RFM Customer Segments",
                    hover_data=["Customer ID", "Frequency"],
                )
                st.plotly_chart(fig, use_container_width=True)
            st.dataframe(segment_summary, use_container_width=True, hide_index=True)

    with tab_basket:
        st.subheader("Market Basket Summary")
        basket_summary = numeric_summary(baskets)
        st.dataframe(basket_summary, use_container_width=True)
        fig = px.histogram(
            baskets,
            x="ItemCount",
            nbins=30,
            title="Distribution of Basket Sizes",
        )
        st.plotly_chart(fig, use_container_width=True)

    with tab_recommendations:
        recommender = ProductRecommender(baskets)
        product_options = sorted(sales["StockCode"].dropna().astype(str).unique().tolist())
        selected_product = None
        if not product_options:
            st.info("No products are available for recommendations.")
        else:
            selected_product = st.selectbox(
                "Choose a product",
                options=product_options,
                key="recommendation_product",
            )
        if selected_product:
            recommendations = recommender.recommend(selected_product, limit=10)
            if recommendations.empty:
                st.warning(
                    "No co-purchase pairs were found for this product. Showing popular products instead."
                )
                recommendations = recommender.popular_products(limit=10)
                recommendations["CoOccurrences"] = recommendations["BasketCount"]
            else:
                recommendations["Support"] = recommendations["CoOccurrences"]
            descriptions = (
                sales[["StockCode", "Description"]]
                .dropna()
                .drop_duplicates("StockCode")
                .astype({"StockCode": "string"})
                .set_index("StockCode")["Description"]
            )
            recommendations["Description"] = recommendations["StockCode"].map(descriptions)
            st.dataframe(recommendations, use_container_width=True, hide_index=True)

    with tab_operations:
        st.subheader("Data Operations")
        if (PROJECT_ROOT / "data" / "raw" / "archive.zip").is_file():
            st.write("Run extraction and preprocessing to refresh all processed datasets.")
            if st.button("Run preprocessing pipeline", type="primary"):
                with st.spinner("Extracting and preprocessing the retail dataset..."):
                    exit_code = run_pipeline([])
                if exit_code == 0:
                    st.cache_data.clear()
                    st.success("Pipeline completed. Reload the page to use refreshed data.")
                else:
                    st.error("Pipeline did not complete successfully.")
        else:
            st.info(
                "The raw archive is not included in this hosted deployment. "
                "Upload the processed CSVs again after restarting the app."
            )

        st.divider()
        st.subheader("MySQL Integration")
        if (PROJECT_ROOT / ".env").is_file():
            if st.button("Test MySQL connection"):
                try:
                    test_connection()
                except Exception as exc:
                    st.error(f"MySQL connection failed: {exc}")
                else:
                    st.success("MySQL connection succeeded.")

            if st.button("Load processed data into MySQL"):
                with st.spinner("Loading processed tables and 1M+ transaction rows..."):
                    try:
                        counts = load_processed_data(
                            PROCESSED_DIR / "cleaned_transactions.csv",
                            PROCESSED_DIR / "customer_rfm.csv",
                        )
                    except Exception as exc:
                        st.error(f"MySQL loading failed: {exc}")
                    else:
                        st.success(f"MySQL load completed: {counts}")
        else:
            st.info(
                "MySQL controls are available for local runs configured with .env. "
                "The hosted dashboard is using uploaded processed CSVs."
            )
